const BY_ISO_CODE = Object.fromEntries(COUNTRIES.map((c) => [c.isoCode, c.name]));
const BY_NAME = Object.fromEntries(COUNTRIES.flatMap((c) => [[c.name.toUpperCase(), c.isoCode], [c.nameAr, c.isoCode]]));

function nameForIsoCode(isoCode) {
  return BY_ISO_CODE[String(isoCode || '').toUpperCase()] || null;
}

function isoCodeForName(name) {
  if (!name) return null;
  const raw = String(name).trim();
  const key = raw.toUpperCase();
  return BY_NAME[key] || BY_NAME[raw] || ALIASES[key] || ALIASES[raw] || (BY_ISO_CODE[key] ? key : null);
}

